import math

# --- Выбор типа сечения ---
while True:
    try:
        menu = int(input('Выберите тип сечения (1-прямоугольное, 2-круглое, 3-двутавр): '))
        if menu in (1, 2, 3):
            break
        print('Повторите ввод (1-3)')
    except ValueError:
        print('Ошибка: введите число')

# --- Ввод размеров с проверкой диапазона ---
def read_value(prompt, lo, hi, cast=float):
    while True:
        try:
            v = cast(input(prompt))
            if lo <= v <= hi:
                return v
            print(f'Неверное значение, введите число от {lo} до {hi}')
        except ValueError:
            print('Ошибка: введите число')

sech = read_value('Введите размеры сечения (10-1000): ', 10, 1000)
iz   = read_value('Введите изгибающий момент (0.1-500): ', 0.1, 500)
nap  = read_value('Введите допускаемое напряжение (50-400): ', 50, 400)
vis  = read_value('Введите высоту палки (10-1000): ', 10, 1000)

# --- Момент сопротивления W (в тех же единицах, что и размеры, мм³) ---
if menu == 1:      # прямоугольник: W = b·h²/6 (здесь b=sech, h=vis)
    W = sech * vis**2 / 6
elif menu == 2:    # круг: W = π·d³/32
    W = math.pi * sech**3 / 32
else:              # двутавр — уточните формулу; пример: W = h³/12 (условно)
    W = vis**3 / 12

# --- Фактическое напряжение σ = M / W (M в Н·м → Н·мм: ×1000) ---
sigma = iz * 1000 / W          # МПа, если W в мм³, M в Н·м

# --- Коэффициент запаса: n = σ_доп / σ_факт ---
n = nap / sigma

if n < 0.5:
    klass = 'большой запас'
elif n <= 1:
    klass = 'допустимо'
else:
    klass = 'перегрузка'

print('\nРезультаты:')
print(f'Тип сечения: {menu}')
print(f'Момент сопротивления W = {W:.2f} мм³')
print(f'Фактическое напряжение σ = {sigma:.2f} МПа')
print(f'Коэффициент запаса n = {n:.3f} — {klass}')